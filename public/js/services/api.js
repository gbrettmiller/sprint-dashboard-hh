// Data fetching and path resolution — all external communication.

export const EARLIEST_FY = 2026;          // No sprint data exists before FY2026
export const EARLIEST_DATE = '2025-10-01'; // Oct 2025 — cutoff for all historical data
export const MONTH_NAMES = ['jan','feb','mar','apr','may','jun','jul','aug','sep','oct','nov','dec'];
export const MONTH_LABELS = ['January','February','March','April','May','June','July','August','September','October','November','December'];

export async function fetchJSON(url) {
  const resp = await fetch(url);
  if (!resp.ok) return null;
  return resp.json();
}

export function dataPath(activeGroup, activeProject, relativePath) {
  if (!activeGroup) return `data/${relativePath}`;
  if (activeProject) return `data/${activeGroup.slug}/${activeProject.slug}/${relativePath}`;
  return `data/${activeGroup.slug}/${relativePath}`;
}

export function resolveGroupAndProject(groupsConfig, groupSlug, projectSlug) {
  if (!groupsConfig || !groupsConfig.groups || groupsConfig.groups.length === 0) {
    return { activeGroup: null, activeProject: null, shouldRedirect: false };
  }

  let activeGroup = null;
  let activeProject = null;

  if (groupSlug) {
    activeGroup = groupsConfig.groups.find(g => g.slug === groupSlug);
  }
  if (!activeGroup) {
    return { activeGroup: null, activeProject: null, shouldRedirect: true };
  }

  if (activeGroup.mode === 'projects') {
    if (projectSlug && activeGroup.projects) {
      activeProject = activeGroup.projects.find(p => p.slug === projectSlug);
    }
    if (!activeProject) {
      return { activeGroup, activeProject: null, shouldRedirect: true };
    }
  }

  return { activeGroup, activeProject, shouldRedirect: false };
}

export function fyMonths(fy, upToDate) {
  const months = [];
  for (let m = 10; m <= 12; m++) months.push({ month: m, year: fy - 1 });
  for (let m = 1; m <= 9; m++) months.push({ month: m, year: fy });
  if (upToDate) {
    const cutoffYear = upToDate.getFullYear();
    const cutoffMonth = upToDate.getMonth() + 1;
    return months.filter(({ month, year }) => year < cutoffYear || (year === cutoffYear && month <= cutoffMonth));
  }
  return months;
}

export function monthFileKey(m, y) {
  return `${String(m).padStart(2, '0')}-${MONTH_NAMES[m - 1]}-${y}`;
}

export async function loadFY(fy, allData, activeGroup, activeProject) {
  if (allData[`fy${fy}`]) return allData[`fy${fy}`];
  const months = fyMonths(fy, new Date());
  const results = {};
  const fetches = months.map(async ({ month, year }) => {
    const key = monthFileKey(month, year);
    const data = await fetchJSON(dataPath(activeGroup, activeProject, `fy${fy}/${key}.json`));
    if (data && data.sprints && data.sprints.length > 0) {
      results[key] = data;
    }
  });
  await Promise.all(fetches);
  allData[`fy${fy}`] = results;
  return results;
}

export async function loadCurrentSprint(activeGroup, activeProject) {
  return fetchJSON(dataPath(activeGroup, activeProject, 'current-sprint.json'));
}

// ---------------------------------------------------------------------------
// Report data (generated by scripts/generate_reports.py)
// ---------------------------------------------------------------------------
export function reportPath(activeGroup, activeProject, relativePath) {
  return dataPath(activeGroup, activeProject, `reports/${relativePath}`);
}

export async function loadSprintReport(activeGroup, activeProject, milestoneSlug) {
  return fetchJSON(reportPath(activeGroup, activeProject, `sprints/${encodeURIComponent(milestoneSlug)}.json`));
}

export async function loadMonthlyReport(activeGroup, activeProject, reportMonthKey) {
  return fetchJSON(reportPath(activeGroup, activeProject, `months/${encodeURIComponent(reportMonthKey)}.json`));
}

// Milestone files live at data/{group}/milestones/{project-slug}/{slug}.json
// (group-scoped, not under the project data dir), so build the path directly.
export async function loadMilestone(activeGroup, activeProject, milestoneSlug) {
  return fetchJSON(dataPath(activeGroup, null, `milestones/${activeProject.slug}/${encodeURIComponent(milestoneSlug)}.json`));
}

export async function discoverFYs(allData, activeGroup, activeProject) {
  const now = new Date();
  const currentFY = now.getMonth() >= 9 ? now.getFullYear() + 1 : now.getFullYear();
  const fys = [];
  for (let fy = currentFY; fy >= EARLIEST_FY; fy--) {
    const data = await loadFY(fy, allData, activeGroup, activeProject);
    if (Object.keys(data).length > 0) fys.push(fy);
  }
  return fys.sort((a, b) => b - a);
}
